#!/usr/bin/env node
// Developer release gate: inspect actual packed bytes, not just source strings.
import crypto from 'node:crypto';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { evaluateReadiness, findLicenseEntries, isValidPrivateField, readinessFailure, resolveReadmeLinks } from './release-readiness.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const LEGACY = /requiresHumanReview|gate:human/g;
const PACKED_TEXT = /^package\/(?:lib\/|src\/|docs\/CONTRACT\.md$|README\.md$|LICENSE$|package\.json$)/;
const ALLOWED_ENTRY = /^package\/(?:lib\/[^/].*|src\/[^/].*|docs\/CONTRACT\.md|README\.md|LICENSE|package\.json)$/;
const DEV_SOURCE = /^(?:bin\/|lib\/scripts\/|evidence\/|docs\/archive\/|scripts\/(?:wt\.|[^/]*worktree)|test\/(?:wt\.|[^/]*worktree))/;
const GIT_CALLERS = new Map([
  ['lib/core/documents/fixed-git.js', /spawnSync\(resolveGitExecutable\(\[root\]\),[\s\S]*?assertReadOnlyGitArgs\(args\)/],
  ['lib/core/documents/external-git.js', /spawnSync\(execPath,[\s\S]*?assertReadOnlyGitArgs\(args\)/],
  ['lib/core/identity/discover.js', /execFileSync\(resolveGitExecutable\(\[boundary\]\),\s*assertReadOnlyGitArgs\(/],
]);
const GIT_SPAWN = /\b(?:spawnSync|spawn|execFileSync|execFile|execSync)\s*\(/g;

export function checkMetadata(metadata, licenseText) {
  if (metadata?.name !== 'dsh-stateboard' || metadata.version !== '0.3.1' || metadata.license !== 'BSD-3-Clause') throw new Error('Release metadata must be dsh-stateboard@0.3.1, BSD-3-Clause');
  if (!isValidPrivateField(metadata.private)) throw new Error('Release metadata private field must be a boolean when present');
  const url = typeof metadata.repository === 'string' ? metadata.repository : metadata.repository?.url;
  if (typeof url !== 'string' || !/^https:\/\/github\.com\/panchongyang\/dsh-stateboard(?:\.git)?\/?$/.test(url) || (metadata.repository && typeof metadata.repository === 'object' && metadata.repository.type !== 'git')) throw new Error('Release repository URL is missing or incorrect');
  if (metadata.bin != null || !Array.isArray(metadata.files) || metadata.files.join('|') !== 'lib/index.js|lib/cordis.patch.yml|lib/client.js|lib/client.js.map|lib/core|lib/host|lib/shared|src|README.md|docs/CONTRACT.md|LICENSE') throw new Error('Release files whitelist or bin registration is incorrect');
  if (typeof licenseText !== 'string' || !licenseText.includes('BSD 3-Clause License') || !licenseText.includes('Copyright (c) 2026 潘重阳') || !licenseText.includes('Neither the name of the copyright holder') || !licenseText.includes('THIS SOFTWARE IS PROVIDED')) throw new Error('BSD-3-Clause LICENSE is missing or incomplete');
  return true;
}

// Tarball contents are untrusted data: never execute them (including in node:vm).
// Compare the complete bundle with the maintainer-selected trusted root's artifact.
// The root is a caller trust decision, never a path taken from archive contents.
// Only client-smoke executes the local artifact's real registration/factory.
// To check a different build, first rebuild it in the corresponding trusted checkout.
export function assertClientIdentity(metadata, source, { root = ROOT } = {}) {
  const manifest = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
  if (typeof manifest.name !== 'string' || !manifest.name.trim()) throw new Error('Client identity requires a trusted manifest name');
  if (metadata?.name !== manifest.name) throw new Error('Client manifest name does not match trusted local manifest name');
  if (typeof source !== 'string' && !Buffer.isBuffer(source)) throw new Error('Client bundle is missing');
  const packedBytes = Buffer.isBuffer(source) ? source : Buffer.from(source, 'utf8');
  const trustedBytes = fs.readFileSync(path.join(root, 'lib/client.js'));
  const trusted = trustedBytes.toString('utf8');
  const prefix = [
    '/* generated by `npm run build:client` from src/client — do not edit */',
    'window.__ModuleLoader__.load({',
    '  id: ' + JSON.stringify(manifest.name) + ',',
    '  factory: function (require) {',
    '    var module = { exports: {} };',
  ].join('\n');
  if (!trusted.startsWith(prefix)) throw new Error('Trusted local client factory id does not match manifest; run npm run build:client and npm run test:client');
  if (!packedBytes.equals(trustedBytes)) throw new Error('Client bundle does not match trusted local artifact bytes; rebuild and test the corresponding trusted checkout');
  return { id: manifest.name, verification: 'trusted-local-byte-match' };
}

export function assertShippedText(text, entry = 'packed file') {
  const rules = [
    ['developer absolute path', /(?:[A-Za-z]:[\\/]+(?:AIWorker|Users[\\/]+[^\\/\s]+)|\/(?:home|Users|d[\\/]AIWorker)\/[^\s'"<>]+)/i],
    ['session/task/project id', /\b(?:tsk|pln|doc|prj|sess|session|task|project)_[a-z0-9]{10,}\b/i],
    ['private network address', /\b(?:10\.(?:\d{1,3}\.){2}\d{1,3}|192\.168\.(?:\d{1,3}\.)\d{1,3}|172\.(?:1[6-9]|2\d|3[01])\.(?:\d{1,3}\.)\d{1,3})\b/],
  ];
  for (const [label, regex] of rules) if (regex.test(text)) throw new Error(entry + ' contains ' + label);
  return true;
}

export function checkGitSurface(files) {
  for (const [name, source] of Object.entries(files)) {
    const count = [...source.replace(/^\s*\/\/.*$/gm, '').matchAll(GIT_SPAWN)].length;
    if (count && (!GIT_CALLERS.has(name) || count !== 1 || !GIT_CALLERS.get(name).test(source))) throw new Error('Unapproved product Git/process invocation: ' + name);
  }
  for (const name of GIT_CALLERS.keys()) if (!files[name] || !GIT_CALLERS.get(name).test(files[name])) throw new Error('Product Git caller changed: ' + name);
  return true;
}

export function checkPublicSource(paths) {
  const found = paths.filter((name) => DEV_SOURCE.test(name.replaceAll('\\', '/')));
  if (found.length) throw new Error('Product-external CLI/worktree tools tracked in public source: ' + found.join(', '));
  return true;
}
// Git-for-Windows ships GNU tar, which reads "D:\..." as a remote host. Prefer
// the Windows system bsdtar so absolute drive paths are always local.
const WINDOWS_TAR = process.platform === 'win32' ? path.join(process.env.SystemRoot || 'C:\\Windows', 'System32', 'tar.exe') : null;
const TAR = WINDOWS_TAR && fs.existsSync(WINDOWS_TAR) ? WINDOWS_TAR : 'tar';

export function checkPackageEntries(entries) {
  if (!Array.isArray(entries) || entries.length === 0) throw new Error('Package is empty');
  const seen = new Set();
  for (const name of entries) {
    if (typeof name !== 'string' || !name.startsWith('package/') || name.includes('\\') || name.includes('\0') || name.split('/').some((part) => part === '.' || part === '..') || seen.has(name)) {
      throw new Error('Unsafe or duplicate archive entry: ' + name);
    }
    seen.add(name);
    const allowedDirectory = name.endsWith('/') && (name === 'package/' || name === 'package/lib/' || name === 'package/src/' || name === 'package/docs/' || /^package\/(?:lib|src)\/(?!scripts\/)[^/]+(?:\/[^/]+)*\/$/.test(name));
    if ((!allowedDirectory && !ALLOWED_ENTRY.test(name)) || /^package\/lib\/scripts\//.test(name)) throw new Error('Developer scripts/tests/docs/evidence/bin or unlisted entry must not ship: ' + name);
  }
  for (const required of ['package/package.json', 'package/README.md', 'package/docs/CONTRACT.md', 'package/LICENSE', 'package/lib/index.js']) {
    if (!seen.has(required)) throw new Error('Required package entry missing: ' + required);
  }
  return entries.filter((name) => PACKED_TEXT.test(name) && !name.endsWith('/'));
}

export function assertPackedReadmeLinks(text, entries) {
  const links = resolveReadmeLinks(text, entries);
  const issues = links.occurrences.filter((item) => item.relative && (item.exists === false || item.reason));
  if (issues.length) throw new Error('Packed README has missing or unsafe relative links: ' + issues.map((item) => item.destination).join(', '));
  if (links.unsupported.length) throw new Error('Packed README has unsupported link syntax: ' + links.unsupported.map((item) => item.kind).join(', '));
  return links.summary;
}

export function assertPureText(text) {
  const matches = [...String(text).matchAll(LEGACY)].map((match) => match[0]);
  if (matches.length) throw new Error('Packed runtime/docs contain legacy gate names: ' + [...new Set(matches)].join(', '));
  return { matches: 0 };
}

function run(file, args, cwd, encoding = 'utf8') {
  const result = spawnSync(file, args, { cwd, encoding, maxBuffer: 64 * 1024 * 1024, windowsHide: true });
  if (result.error) throw result.error;
  if (result.status !== 0) throw new Error(path.basename(file) + ' failed (' + result.status + '): ' + result.stderr);
  return result.stdout;
}

export function inspectTarball(tarball, { root = ROOT } = {}) {
  const archive = path.resolve(tarball);
  if (!fs.lstatSync(archive).isFile() || fs.lstatSync(archive).isSymbolicLink()) throw new Error('Tarball must be a regular file');
  const entries = run(TAR, ['-tf', archive], path.dirname(archive)).split(/\r?\n/).filter(Boolean);
  const selected = checkPackageEntries(entries);
  const types = readTarTypes(archive, entries);
  for (const entry of entries) if (types[entry]?.type !== 'file') throw new Error('Packed entry must be a regular file: ' + entry);
  const texts = Object.fromEntries(selected.map((entry) => [entry, run(TAR, ['-xOf', archive, entry], path.dirname(archive))]));
  for (const [entry, text] of Object.entries(texts)) {
    assertPureText(text);
    assertShippedText(text, entry);
  }
  const metadata = JSON.parse(texts['package/package.json']);
  checkMetadata(metadata, texts['package/LICENSE']);
  const clientBytes = run(TAR, ['-xOf', archive, 'package/lib/client.js'], path.dirname(archive), null);
  const clientIdentity = assertClientIdentity(metadata, clientBytes, { root });
  const readmeLinks = assertPackedReadmeLinks(texts['package/README.md'], entries);
  checkGitSurface(Object.fromEntries(Object.entries(texts).filter(([entry]) => entry.startsWith('package/lib/') && entry.endsWith('.js')).map(([entry, text]) => [entry.slice('package/'.length), text])));
  return { schemaVersion: 1, mode: 'purity', ok: true, tarball: archive, sha256: crypto.createHash('sha256').update(fs.readFileSync(archive)).digest('hex'), entries: entries.length, scannedFiles: selected.length, legacyMatches: 0, readmeLinks, clientIdentity, checks: ['pack-whitelist', 'regular-files', 'legacy-gate', 'shipped-secrets', 'metadata-license', 'git-allowlist', 'readme-links', 'client-identity'] };
}

export function checkReleasePurity({ root = ROOT, tarball = null } = {}) {
  if (tarball) return inspectTarball(tarball, { root });
  checkPublicSource(run('git', ['ls-files', '--cached', '-z'], root).split('\0').filter(Boolean));
  const npmCli = process.env.npm_execpath;
  if (!npmCli || !fs.existsSync(npmCli)) throw new Error('Run this gate via npm run check:release, or pass --tarball <archive>');
  const output = fs.mkdtempSync(path.join(os.tmpdir(), 'pb-release-purity-'));
  const packed = JSON.parse(run(process.execPath, [npmCli, 'pack', '--ignore-scripts', '--json', '--pack-destination', output], root));
  if (!Array.isArray(packed) || packed.length !== 1 || typeof packed[0].filename !== 'string' || path.basename(packed[0].filename) !== packed[0].filename) throw new Error('Unexpected npm pack result');
  return inspectTarball(path.join(output, packed[0].filename), { root });
}

const USAGE = 'Usage: npm run check:release [-- --tarball <archive>] | npm run check:release:readiness [-- --tarball <archive>]';

function readTarText(archive, entries) {
  return run(TAR, ['-xOf', archive, ...entries], path.dirname(archive));
}

function readTarTypes(archive, entries) {
  const lines = run(TAR, ['-tvf', archive], path.dirname(archive)).split(/\r?\n/).filter(Boolean);
  if (lines.length !== entries.length) throw new Error('tar verbose listing count mismatch: ' + lines.length + ' lines for ' + entries.length + ' entries');
  const types = {};
  for (let index = 0; index < entries.length; index++) {
    const name = entries[index];
    const line = lines[index];
    const arrow = line.indexOf(' -> ');
    const head = arrow === -1 ? line : line.slice(0, arrow);
    if (!head.endsWith(' ' + name)) {
      // The plain and verbose listings are paired in archive order. If the
      // verbose line cannot be attributed exactly, fail closed instead of
      // letting a name suffix borrow another entry's type.
      types[name] = { type: 'unknown', linkTarget: null };
      continue;
    }
    const kind = line[0] === '-' ? 'file' : line[0] === 'l' ? 'symlink' : line[0] === 'd' ? 'dir' : 'other';
    types[name] = { type: kind, linkTarget: arrow === -1 ? null : line.slice(arrow + 4) };
  }
  return types;
}

export function inspectReadiness(tarball) {
  const archive = path.resolve(tarball);
  if (!fs.lstatSync(archive).isFile() || fs.lstatSync(archive).isSymbolicLink()) throw new Error('Tarball must be a regular file');
  const entries = run(TAR, ['-tf', archive], path.dirname(archive)).split(/\r?\n/).filter(Boolean);
  const entryTypes = readTarTypes(archive, entries);
  let archiveError = null;
  try {
    checkPackageEntries(entries);
  } catch (error) {
    archiveError = error.message;
  }
  const packed = entries.filter((name) => PACKED_TEXT.test(name) && !name.endsWith('/'));
  const legacyMatches = packed.length ? [...readTarText(archive, packed).matchAll(LEGACY)].length : 0;
  let packageJson = null;
  let packageJsonError = null;
  try {
    packageJson = JSON.parse(readTarText(archive, ['package/package.json']));
  } catch (error) {
    packageJsonError = 'package/package.json unreadable or invalid: ' + error.message;
  }
  let readmeText = null;
  let readmeError = null;
  try {
    readmeText = readTarText(archive, ['package/README.md']);
  } catch (error) {
    readmeError = error.message;
  }
  const licenseFiles = findLicenseEntries(entries).map((entry) => {
    let content = null;
    try {
      content = readTarText(archive, [entry]);
    } catch (error) {
      content = null;
    }
    return { entry, content };
  });
  return evaluateReadiness({
    entries,
    packageJson,
    packageJsonError,
    readmeText,
    readmeError,
    legacyMatches,
    archiveError,
    entryTypes,
    licenseFiles,
    tarball: {
      path: archive,
      sha256: crypto.createHash('sha256').update(fs.readFileSync(archive)).digest('hex'),
      bytes: fs.statSync(archive).size,
      entries: entries.length,
    },
  });
}

export function checkReleaseReadiness({ root = ROOT, tarball = null } = {}) {
  if (tarball) return inspectReadiness(tarball);
  const npmCli = process.env.npm_execpath;
  if (!npmCli || !fs.existsSync(npmCli)) throw new Error('Run this gate via npm run check:release:readiness, or pass --tarball <archive>');
  const output = fs.mkdtempSync(path.join(os.tmpdir(), 'pb-release-readiness-'));
  const packed = JSON.parse(run(process.execPath, [npmCli, 'pack', '--ignore-scripts', '--json', '--pack-destination', output], root));
  if (!Array.isArray(packed) || packed.length !== 1 || typeof packed[0].filename !== 'string' || path.basename(packed[0].filename) !== packed[0].filename) throw new Error('Unexpected npm pack result');
  return inspectReadiness(path.join(output, packed[0].filename));
}

function parseCliArgs(args) {
  let readiness = false;
  let tarball = null;
  for (let i = 0; i < args.length; i++) {
    if (args[i] === '--readiness') {
      readiness = true;
      continue;
    }
    if (args[i] === '--tarball') {
      const value = args[i + 1];
      if (!value || value.startsWith('--')) return { readiness, tarball, error: '--tarball requires a value' };
      tarball = value;
      i++;
      continue;
    }
    return { readiness, tarball, error: 'unknown argument: ' + args[i] };
  }
  return { readiness, tarball, error: null };
}

if (process.argv[1] && path.resolve(process.argv[1]).toLowerCase() === fileURLToPath(import.meta.url).toLowerCase()) {
  const args = process.argv.slice(2);
  const parsed = parseCliArgs(args);
  if (parsed.error) {
    if (parsed.readiness || args.includes('--readiness')) {
      console.log(JSON.stringify(readinessFailure(parsed.error + ' | ' + USAGE), null, 2));
      console.error('[release-readiness] ' + parsed.error);
    } else {
      console.log(JSON.stringify({ schemaVersion: 1, mode: 'purity', ok: false, error: parsed.error + ' | ' + USAGE }, null, 2));
      console.error('[release-purity] FAIL: ' + parsed.error + ' | ' + USAGE);
    }
    process.exitCode = 1;
  } else if (parsed.readiness) {
    try {
      const result = checkReleaseReadiness({ tarball: parsed.tarball });
      console.log(JSON.stringify(result, null, 2));
      if (!result.ready) process.exitCode = 1;
    } catch (error) {
      console.log(JSON.stringify(readinessFailure(error.message), null, 2));
      console.error('[release-readiness] ' + error.message);
      process.exitCode = 1;
    }
  } else {
    try {
      const result = checkReleasePurity({ tarball: parsed.tarball });
      console.log(JSON.stringify(result, null, 2));
      console.error('[release-purity] PASS: ' + result.entries + ' package entries, ' + result.scannedFiles + ' files scanned; ' + result.checks.length + ' technical checks');
    } catch (error) {
      console.log(JSON.stringify({ schemaVersion: 1, mode: 'purity', ok: false, error: error.message }, null, 2));
      console.error('[release-purity] FAIL: ' + error.message);
      process.exitCode = 1;
    }
  }
}
